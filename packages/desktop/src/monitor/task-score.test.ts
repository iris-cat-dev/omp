function taskAssertClose(
  actual: unknown,
  expected: unknown,
  label = "result",
  tolerance = 1e-9,
): void {
  if (typeof expected === "number") {
    expect(actual, label).toBeTypeOf("number");
    expect(Math.abs((actual as number) - expected), label).toBeLessThanOrEqual(tolerance);
  } else if (Array.isArray(expected)) {
    expect(Array.isArray(actual), label).toBe(true);
    expect((actual as unknown[]).length, label + ".length").toBe(expected.length);
    expected.forEach((value, index) =>
      taskAssertClose((actual as unknown[])[index], value, label + "[" + index + "]", tolerance),
    );
  } else if (expected !== null && typeof expected === "object") {
    expect(actual !== null && typeof actual === "object", label).toBe(true);
    expect(Object.keys(actual as object).sort(), label + ".keys").toEqual(
      Object.keys(expected).sort(),
    );
    for (const [key, value] of Object.entries(expected)) {
      taskAssertClose(
        (actual as Record<string, unknown>)[key],
        value,
        label + "." + key,
        tolerance,
      );
    }
  } else expect(actual, label).toBe(expected);
}

